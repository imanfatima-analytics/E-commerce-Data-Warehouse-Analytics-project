USE DATABASE ECOMMERCE_DW;
USE SCHEMA WAREHOUSE;

-- 1. Load Customer Dimension
INSERT INTO DIM_CUSTOMER (
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    EMAIL
)
SELECT DISTINCT
    CUSTOMER_ID,
    'Customer ' || CUSTOMER_ID,
    INITCAP(TRIM(CITY)),
    NULL
FROM STAGING_SALES;

-- 2. Load Product Dimension
INSERT INTO DIM_PRODUCT (
    PRODUCT_ID,
    PRODUCT_NAME,
    CATEGORY,
    PRODUCT_PRICE
)
SELECT DISTINCT
    PRODUCT_ID,
    TRIM(PRODUCT_NAME),
    INITCAP(TRIM(CATEGORY)),
    UNIT_PRICE
FROM STAGING_SALES;

-- 3. Load Date Dimension
INSERT INTO DIM_DATE (
    DATE_KEY,
    FULL_DATE,
    DAY,
    MONTH,
    MONTH_NAME,
    QUARTER,
    YEAR
)
SELECT DISTINCT
    TO_NUMBER(TO_CHAR(ORDER_DATE, 'YYYYMMDD')),
    ORDER_DATE,
    DAY(ORDER_DATE),
    MONTH(ORDER_DATE),
    MONTHNAME(ORDER_DATE),
    'Q' || QUARTER(ORDER_DATE),
    YEAR(ORDER_DATE)
FROM STAGING_SALES
WHERE ORDER_DATE IS NOT NULL;

-- 4. Load Sales Fact
INSERT INTO FACT_SALES (
    ORDER_ID,
    CUSTOMER_KEY,
    PRODUCT_KEY,
    DATE_KEY,
    QUANTITY,
    SALES_AMOUNT,
    COST_AMOUNT,
    PROFIT
)
SELECT
    s.ORDER_ID,
    c.CUSTOMER_KEY,
    p.PRODUCT_KEY,
    d.DATE_KEY,
    s.QUANTITY,
    s.SALES_AMOUNT,
    s.COST_AMOUNT,
    s.PROFIT
FROM STAGING_SALES s
JOIN DIM_CUSTOMER c
    ON s.CUSTOMER_ID = c.CUSTOMER_ID
JOIN DIM_PRODUCT p
    ON s.PRODUCT_ID = p.PRODUCT_ID
JOIN DIM_DATE d
    ON s.ORDER_DATE = d.FULL_DATE;
